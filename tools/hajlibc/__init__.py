"""hajlibc pages: data.js and the tests, coverage and docs reports.

Called by main.py (step `hajlibc`). Inputs, nothing is hard-coded:
    hajlibc       the hajlibc git repository (external/hajlibc)
    tests_dir     blåsix output of a normal run   (<dir>/<target>/results.json)
    coverage_dir  blåsix output of a coverage run (<dir>/<target>/coverage/lines.tsv)
    posix_dir     POSIX tracker output            (<dir>/summary.json)

Outputs, under `out` (dist/projects/hajlibc):
    data.js       window.HAJLIBC_DATA, read by hajlibc.js on the hajlibc page
    tests/        every test with its status, conformance per header
    coverage/     line coverage per directory and per file
    docs/         API reference from the headers' doc comments
"""
from __future__ import annotations

import json
import shutil
from datetime import datetime, timezone
from pathlib import Path
from typing import TYPE_CHECKING

from .docs import load_docs
from .inputs import load_coverage, load_posix, load_tests, repo_info
from .model import HajlibcData
from .pages import coverage_page, docs_index_page, header_doc_page, slug, tests_page

if TYPE_CHECKING:
    from tools.render import Site

__all__ = ["build"]


def build(site: Site, hajlibc: Path, tests_dir: Path, coverage_dir: Path, posix_dir: Path, out: Path) -> list[str]:
    """Write data.js and the report pages under `out`; returns what was written.

    Each input may be missing: its pages are skipped and data.js says so
    (the hajlibc page then shows how to generate it).
    """
    repo = repo_info(hajlibc)
    tests = load_tests(tests_dir)
    coverage = load_coverage(coverage_dir)
    docs = load_docs(hajlibc)
    posix = load_posix(posix_dir)

    out.mkdir(parents=True, exist_ok=True)
    for name in ("tests", "coverage", "docs"):
        if (out / name).exists():
            shutil.rmtree(out / name)

    if tests:
        site.render("report.html", out / "tests" / "index.html", **tests_page(tests, repo))
    if coverage:
        site.render("report.html", out / "coverage" / "index.html", **coverage_page(coverage, repo))
    if docs:
        site.render("report.html", out / "docs" / "index.html", **docs_index_page(docs, repo))
        for header, doc in docs.items():
            site.render("report.html", out / "docs" / f"{slug(header)}.html", **header_doc_page(header, doc))

    data: HajlibcData = {
        "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "repo": repo,
        "posix": posix,
        "tests": tests["summary"] if tests else None,
        "coverage": coverage["summary"] if coverage else None,
        "docs": {
            "headers": [{"name": h, "slug": slug(h), "brief": d["brief"], "count": len(d["entries"])}
                        for h, d in docs.items()],
            "declarations": sum(len(d["entries"]) for d in docs.values()),
        } if docs else None,
    }
    (out / "data.js").write_text(
        "// Generated by tools/hajlibc (main.py, step hajlibc): do not edit by hand.\n"
        f"window.HAJLIBC_DATA = {json.dumps(data, separators=(',', ':'))};\n")

    parts = {"tests": tests, "coverage": coverage, f"docs ({len(docs)} headers)": docs, "posix summary": posix}
    return ["data.js", *(name for name, present in parts.items() if present)]
