"""hajlibc pages: data.js and the tests, coverage and docs reports.

Called by main.py (step `hajlibc`). Inputs, nothing is hard-coded:
    hajlibc       the hajlibc git repository (external/hajlibc)
    blasix        the blåsix git repository (links to the tests' sources)
    tests_dir     blåsix output of a normal run   (<dir>/<target>/results.json)
    coverage_dir  blåsix output of a coverage run (<dir>/<target>/coverage/lcov.info)
    posix_dir     POSIX tracker output            (<dir>/summary.json)

Outputs, under `out` (dist/projects/hajlibc):
    data.js       window.HAJLIBC_DATA, read by hajlibc.js on the hajlibc page
    tests/        recap (per header, every interface, failing tests) and one
                  page per header: its interfaces, their tests, the failures
    coverage/     recap per category, one page per category, one per source
                  file with its lines marked run or not; lcov.info
    docs/         API reference from the headers' doc comments
"""
from __future__ import annotations

import json
import shutil
from datetime import datetime, timezone
from pathlib import Path
from typing import TYPE_CHECKING, Callable

from tools import lcov
from .coverage_pages import coverage_category, coverage_file, coverage_index, file_page
from .docs import load_docs
from .inputs import load_coverage, load_posix, load_tests, repo_info, slug
from .model import HajlibcData
from .pages import docs_index_page, header_doc_page
from .tests_pages import tests_header, tests_index

if TYPE_CHECKING:
    from tools.render import Site

__all__ = ["build"]


def build(site: Site, hajlibc: Path, blasix: Path, tests_dir: Path, coverage_dir: Path, posix_dir: Path,
          out: Path, warn: Callable[[str], None]) -> list[str]:
    """Write data.js and the report pages under `out`; returns what was written.

    Each input may be missing: its pages are skipped and data.js says so
    (the hajlibc page then shows how to generate it).
    """
    repo = repo_info(hajlibc)
    suite = repo_info(blasix)
    tests = load_tests(tests_dir, warn)
    coverage = load_coverage(coverage_dir, hajlibc, warn)
    docs = load_docs(hajlibc)
    posix = load_posix(posix_dir)

    out.mkdir(parents=True, exist_ok=True)
    for name in ("tests", "coverage", "docs"):
        if (out / name).exists():
            shutil.rmtree(out / name)

    if tests:
        site.render("reports/tests.html", out / "tests" / "index.html", **tests_index(tests, repo, suite))
        for row in tests["conformance"]:
            site.render("reports/tests-header.html", out / "tests" / f"{row['slug']}.html",
                        **tests_header(tests, row, suite))
    if coverage:
        cov = out / "coverage"
        site.render("reports/coverage.html", cov / "index.html", **coverage_index(coverage, repo))
        lcov.relocate(Path(coverage["tracefile"]), hajlibc, cov / "lcov.info")
        slugs = {c["name"]: c["slug"] for c in coverage["summary"]["categories"]}
        for category in coverage["summary"]["categories"]:
            site.render("reports/coverage-category.html", cov / f"{category['slug']}.html",
                        **coverage_category(coverage, category))
        for f in coverage["files"]:
            site.render("reports/coverage-file.html", cov / file_page(f["path"]),
                        **coverage_file(f, hajlibc, repo, slugs[f["category"]]))
    if docs:
        site.render("report.html", out / "docs" / "index.html", **docs_index_page(docs, repo))
        for header, doc in docs.items():
            site.render("report.html", out / "docs" / f"{slug(header)}.html", **header_doc_page(header, doc))

    data: HajlibcData = {
        "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "repo": repo,
        "posix": posix,
        "tests": tests["summary"] if tests else None,
        "coverage": coverage["summary"] if coverage else None,
        "docs": {
            "headers": [{"name": h, "slug": slug(h), "brief": d["brief"], "count": len(d["entries"])}
                        for h, d in docs.items()],
            "declarations": sum(len(d["entries"]) for d in docs.values()),
        } if docs else None,
    }
    (out / "data.js").write_text(
        "// Generated by tools/hajlibc (main.py, step hajlibc): do not edit by hand.\n"
        f"window.HAJLIBC_DATA = {json.dumps(data, separators=(',', ':'))};\n")

    parts = {
        f"tests ({len(tests['conformance'])} headers)" if tests else "tests": tests,
        f"coverage ({len(coverage['files'])} files)" if coverage else "coverage": coverage,
        f"docs ({len(docs)} headers)": docs,
        "posix summary": posix,
    }
    return ["data.js", *(name for name, present in parts.items() if present)]
