/**
 * Astronomical data, as plain tables.
 *
 * Constellations: real stars (right ascension in hours, declination in
 * degrees, visual magnitude) and the usual stick figure as index pairs.
 *
 * Moon: the near side as seen from the northern hemisphere, on the unit disk
 * (x right, y down), from selenographic coordinates.
 */

/** [right ascension (h), declination (°), magnitude] */
export type Star = readonly [ra: number, dec: number, mag: number];
/** Indices of two stars of the same constellation. */
export type Segment = readonly [from: number, to: number];

export interface ConstellationData {
  readonly name: string;
  readonly stars: readonly Star[];
  readonly lines: readonly Segment[];
}

